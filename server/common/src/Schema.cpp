// The original server's layout: its tables under its names in lower case, one
// schema per original database, our own state in sr_ tables. Each migration is applied once, in
// order; never edit one that has shipped: add the next. The original's tables are made only when
// missing (an imported database keeps its own), and never changed: indexes we need are added,
// columns never.
//
// Types as maps them (tinyint -> smallint, datetime -> timestamp,
// nvarchar -> varchar, identity -> GENERATED BY DEFAULT AS IDENTITY). Names and columns are the
// 1.188 shard's, as its backup holds them.
struct Migration {
    int version;
    const char* sql;
};

