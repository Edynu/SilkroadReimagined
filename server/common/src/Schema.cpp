bool ValidSchemaName(std::string_view name) {
    if (name.empty() || name.size() > 63 || std::isdigit(static_cast<unsigned char>(name[0]))) return false;
    for (char c : name) {
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_')) return false;
    }
    return true;
}

int LatestSchemaVersion() { return std::end(kAccountMigrations)[-1].version; }
int LatestShardSchemaVersion() { return std::end(kShardMigrations)[-1].version; }

int SchemaVersion(Database& db) { return Applied(db, kAccountSchema); }

int ShardSchemaVersion(Database& db, const std::string& shardSchema) {
    return ValidSchemaName(shardSchema) ? Applied(db, shardSchema) : 0;
}

bool MigrateSchema(Database& db, std::string& error) { return MigrateSchema(db, kDefaultShardSchema, error); }

bool MigrateSchema(Database& db, const std::string& shardSchema, std::string& error) {
    if (!ValidSchemaName(shardSchema)) {
        error = "not a schema name: " + shardSchema;
        return false;
    }
    if (!Migrate(db, kAccountSchema, kAccountMigrations, error)) return false;
    if (!Migrate(db, shardSchema, kShardMigrations, error)) return false;
    if (!Migrate(db, LogSchemaOf(shardSchema), kLogMigrations, error)) return false;
    // Names without a schema find the shard's tables, then the account's: this connection, and
    // (the first shard) every new one to this database. The latter needs the database's owner;
    // the servers set their own path anyway (WithSearchPath).
    const std::string path = std::format("{}, {}, public", shardSchema, kAccountSchema);
    if (!db.Query(std::format("SET search_path TO {}", path)).Ok()) {
        error = "search_path";
        return false;
    }
    if (shardSchema == kDefaultShardSchema) {
        db.Query(std::format("DO $$ BEGIN EXECUTE format('ALTER DATABASE %I SET search_path TO {}', current_database()); "
                             "EXCEPTION WHEN insufficient_privilege THEN NULL; END $$",
                             path));
    }
    return true;
}

