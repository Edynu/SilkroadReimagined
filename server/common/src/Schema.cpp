constexpr std::int64_t kMigrationLock = 0x5352'4F4D'4947; // "SROMIG"

int Applied(Database& db, const std::string& schema) {
    QueryResult r = db.Query(std::format("SELECT coalesce(max(version), 0) FROM {}.sr_schema_migrations", schema));
    return r.Ok() && r.Rows() == 1 ? int(r.Int(0, 0)) : 0;
}

// Applies `migrations` to `schema` (made if missing), with its own ledger.
template <std::size_t N>
bool Migrate(Database& db, const std::string& schema, const Migration (&migrations)[N], std::string& error) {
    QueryResult made = db.Script(std::format("CREATE SCHEMA IF NOT EXISTS {0}; "
                                             "CREATE TABLE IF NOT EXISTS {0}.sr_schema_migrations ("
                                             "  version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())",
                                             schema));
    if (!made.Ok()) {
        // Two servers starting at once can race to make the schema: the loser's error is fine if it is there now.
        if (!db.Query("SELECT to_regclass($1) IS NOT NULL", {schema + ".sr_schema_migrations"}).Bool(0, 0)) {
            error = std::format("{}: {}", schema, made.Error());
            return false;
        }
    }
    for (const Migration& m : migrations) {
        const bool ok = db.Transaction(
            [&](Database& tx) {
                QueryResult lock = tx.Query("SELECT pg_advisory_xact_lock($1)", {kMigrationLock});
                if (!lock.Ok()) {
                    error = lock.Error();
                    return false;
                }
                QueryResult applied = tx.Query(std::format("SELECT 1 FROM {}.sr_schema_migrations WHERE version = $1", schema), {m.version});
                if (!applied.Ok()) {
                    error = applied.Error();
                    return false;
                }
                if (applied.Rows() == 1) return true;
                // The migration's names land in its schema (and nowhere else).
                if (!tx.Query(std::format("SET LOCAL search_path TO {}", schema)).Ok()) return false;
                QueryResult run = tx.Script(m.sql);
                if (!run.Ok()) {
                    error = std::format("{} migration {}: {}", schema, m.version, run.Error());
                    return false;
                }
                QueryResult record = tx.Query(std::format("INSERT INTO {}.sr_schema_migrations (version) VALUES ($1)", schema), {m.version});
                if (!record.Ok()) {
                    error = record.Error();
                    return false;
                }
                return true;
            },
            error);
        if (!ok) return false;
    }
    return true;
}

