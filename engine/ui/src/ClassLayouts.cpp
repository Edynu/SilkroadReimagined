std::string_view LayoutOfClass(std::string_view className) {
    const auto it = std::lower_bound(std::begin(kTable), std::end(kTable), className,
                                     [](const auto& row, std::string_view name) { return row.first < name; });
    return it != std::end(kTable) && it->first == className ? it->second : std::string_view{};
}

std::size_t ClassLayoutCount() { return std::size(kTable); }

std::string_view ClassOfLayout(std::string_view layoutPath) {
    for (const auto& [className, layout] : kTable) {
        if (layout == layoutPath) return className;
    }
    return {};
}

